"""Run the whole pipeline: raw -> staging -> clean -> checks -> report.

    python run_pipeline.py                 # builds ./itus_pipeline.db
    python run_pipeline.py --db other.db   # somewhere else

Safe to rerun: raw files are skipped when unchanged, staging and clean are
rebuilt deterministically from raw, so the output is identical every time.
"""
import argparse
import sqlite3
import time
from datetime import datetime, timezone
from pathlib import Path

import checks
from itus import config
from itus.clean import build_fact
from itus.dq import DQLog
from itus.identity import build_identity
from itus.raw import load_raw
from itus.staging import build_staging


def run(db_path=config.DB_PATH, raw_dir=config.RAW_DIR, report_dir=config.OUTPUT_DIR, verbose=True):
    say = print if verbose else (lambda *a, **k: None)
    t0 = time.time()
    started = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")
    conn = sqlite3.connect(db_path)
    try:
        # FKs are declared for documentation but not enforced (layers are dropped and
        # rebuilt each run); referential integrity is asserted by the integrity checks.
        loaded, skipped = load_raw(conn, Path(raw_dir))
        say(f"raw:      {len(loaded)} files loaded, {len(skipped)} unchanged")

        dq = DQLog()
        resolver, companies = build_identity(conn, dq)
        say(f"identity: {len(companies)} companies")

        rows = build_staging(conn, resolver, companies, dq)
        n_q = sum(r.quarantined for r in rows)
        say(f"staging:  {len(rows)} rows, {n_q} quarantined")

        n_fact = build_fact(conn, dq)
        dq.write(conn)
        say(f"clean:    {n_fact} fact versions, {len(dq.entries)} data-quality log entries")

        results = checks.run_checks(conn)
        if verbose:
            print()
            checks.print_results(results)

        integrity_failures = [r["name"] for r in results
                              if r["category"] == "integrity" and r["status"] != "PASS"]

        with conn:
            conn.execute(
                """CREATE TABLE IF NOT EXISTS pipeline_runs (
                    run_id INTEGER PRIMARY KEY, started_at TEXT, finished_at TEXT,
                    files_loaded INTEGER, files_skipped INTEGER, staged_rows INTEGER,
                    quarantined_rows INTEGER, fact_rows INTEGER, dq_log_entries INTEGER,
                    checks_failed INTEGER)"""
            )
            conn.execute(
                "INSERT INTO pipeline_runs (started_at, finished_at, files_loaded, files_skipped,"
                " staged_rows, quarantined_rows, fact_rows, dq_log_entries, checks_failed)"
                " VALUES (?,?,?,?,?,?,?,?,?)",
                (started, datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S"), len(loaded),
                 len(skipped), len(rows), n_q, n_fact, len(dq.entries),
                 sum(r["status"] == "FAIL" for r in results)),
            )

        if report_dir:
            write_report(conn, results, Path(report_dir))
            say(f"\nreport:   {Path(report_dir) / 'dq_report.md'}")
        say(f"done in {time.time() - t0:.1f}s -> {db_path}")

        if integrity_failures:
            raise SystemExit(f"clean-layer integrity checks failed: {integrity_failures}")
        return results
    finally:
        conn.close()


def write_report(conn, results, out_dir):
    out_dir.mkdir(parents=True, exist_ok=True)
    lines = ["# Data quality report", "",
             "Generated by `python run_pipeline.py`. Source checks run on staging (what the vendor sent);",
             "integrity checks run on the clean layer. FAIL/WARN on a source check = a real problem in the",
             "files, which the pipeline quarantined or flagged.", "",
             "## Checks", "",
             "| check | category | severity | threshold | actual | status |",
             "|---|---|---|---|---|---|"]
    for r in results:
        thr = "-" if r["threshold"] is None else r["threshold"]
        lines.append(f"| `{r['name']}` | {r['category']} | {r['severity']} | {thr} | {r['actual']} | {r['status']} |")

    lines += ["", "## Issues logged (data_quality_log)", "",
              "| code | severity | action | count |", "|---|---|---|---|"]
    for code, sev, action, n in conn.execute(
            "SELECT check_code, severity, action, COUNT(*) FROM data_quality_log"
            " GROUP BY 1,2,3 ORDER BY CASE severity WHEN 'error' THEN 0 WHEN 'warn' THEN 1 ELSE 2 END, 1"):
        lines.append(f"| {code} | {sev} | {action} | {n} |")

    lines += ["", "## Quarantine", "", "| reason | rows |", "|---|---|"]
    for reason, n in conn.execute("SELECT reason_codes, COUNT(*) FROM quarantine GROUP BY 1 ORDER BY 2 DESC"):
        lines.append(f"| {reason} | {n} |")

    lines += ["", "## Row-level issues (excluding whole-file quarantine)", "",
              "| file | row | company | period | code | message |", "|---|---|---|---|---|---|"]
    for f, rn, cid, p, code, msg in conn.execute(
            """SELECT source_file, row_number, company_id, period, check_code, message
               FROM data_quality_log
               WHERE row_number IS NOT NULL AND check_code NOT IN ('FILE_PERIOD_MISMATCH', 'REVISION')
                 AND source_file NOT IN (SELECT file_name FROM stg_file
                                         WHERE content_periods IS NOT file_period)
               ORDER BY source_file, row_number"""):
        lines.append(f"| {f} | {rn} | {cid or ''} | {p or ''} | {code} | {msg} |")

    (out_dir / "dq_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--db", default=str(config.DB_PATH))
    ap.add_argument("--raw-dir", default=str(config.RAW_DIR))
    args = ap.parse_args()
    run(args.db, args.raw_dir)
